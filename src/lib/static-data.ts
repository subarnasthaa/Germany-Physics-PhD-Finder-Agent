// HELPER: Get institutions by type
// ─────────────────────────────────────────────
export function getInstitutionsByType(type: Institution['type']): Institution[] {
  return institutions.filter(i => i.type === type)
}

// ─────────────────────────────────────────────
// HELPER: Get institutions by state
// ─────────────────────────────────────────────
export function getInstitutionsByState(state: string): Institution[] {
  return institutions.filter(i => i.state === state)
}

// ─────────────────────────────────────────────
// HELPER: Get institutions by field
// ─────────────────────────────────────────────
export function getInstitutionsByField(field: string): Institution[] {
  return institutions.filter(i => i.fields.toLowerCase().includes(field.toLowerCase()))
}

// ─────────────────────────────────────────────
// HELPER: Get watchlisted institutions
// ─────────────────────────────────────────────
export function getWatchlistedInstitutions(): Institution[] {
  return institutions.filter(i => i.watchlisted)
}

// ─────────────────────────────────────────────
// HELPER: Get scholarships by category
// ─────────────────────────────────────────────
export function getScholarshipsByCategory(category: ScholarshipInfo['category']): ScholarshipInfo[] {
  return scholarships.filter(s => s.category === category)
}

// ─────────────────────────────────────────────
// HELPER: Get all unique states
// ─────────────────────────────────────────────
export function getUniqueStates(): string[] {
  return Array.from(new Set(institutions.map(i => i.state))).sort()
}

// ─────────────────────────────────────────────
// HELPER: Get all unique fields
// ─────────────────────────────────────────────
export function getUniqueFields(): string[] {
  const allFields = institutions.flatMap(i => i.fields.split('|'))
  return Array.from(new Set(allFields.map(f => f.trim()))).sort()
}

// ─────────────────────────────────────────────
// HELPER: Get IMPRS programs
// ─────────────────────────────────────────────
export function getIMPRSPrograms(): Institution[] {
  return institutions.filter(i => i.phdType === 'IMPRS' || i.phdType.includes('IMPRS'))
}

// ─────────────────────────────────────────────
// HELPER: Get English-only programs
// ─────────────────────────────────────────────
export function getEnglishOnlyPrograms(): Institution[] {
  return institutions.filter(i => i.languageInstruction === 'English')
}

// ─────────────────────────────────────────────
// HELPER: Search institutions
// ─────────────────────────────────────────────
export function searchInstitutions(query: string): Institution[] {
  const q = query.toLowerCase()
  return institutions.filter(i =>
    i.name.toLowerCase().includes(q) ||
    i.city.toLowerCase().includes(q) ||
    i.state.toLowerCase().includes(q) ||
    i.fields.toLowerCase().includes(q) ||
    i.department.toLowerCase().includes(q) ||
    (i.researchGroup && i.researchGroup.toLowerCase().includes(q)) ||
    i.notableProfessors.toLowerCase().includes(q) ||
    i.notesForNepali.toLowerCase().includes(q)
  )
}

// ─────────────────────────────────────────────
// HELPER: Search scholarships
// ─────────────────────────────────────────────
export function searchScholarships(query: string): ScholarshipInfo[] {
  const q = query.toLowerCase()
  return scholarships.filter(s =>
    s.title.toLowerCase().includes(q) ||
    s.category.toLowerCase().includes(q) ||
    s.content.toLowerCase().includes(q)
  )
}
